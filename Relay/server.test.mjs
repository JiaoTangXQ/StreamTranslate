import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes,createCipheriv,createDecipheriv,createECDH,hkdfSync} from 'node:crypto';
import {createRelay} from './server.mjs';

const token=()=>randomBytes(32).toString('hex');
test('private encrypted relay: auth, invitation, replay, ordering, revocation',async()=>{
  const secret=token(), room=token(), ticket=token(), key=randomBytes(32);
  const relay=createRelay({secret,origin:'http://127.0.0.1:18449',assets:new Map(),insecureTest:true});
  await new Promise(resolve=>relay.listen(18449,'127.0.0.1',resolve));
  const origin='http://127.0.0.1:18449';
  const call=(path,body,extra={})=>fetch(origin+path,{method:body===undefined?'GET':'POST',headers:{Origin:origin,...(body===undefined?{}:{'Content-Type':'application/json'}),...extra},body:body===undefined?undefined:JSON.stringify(body)});
  const pub=(op,body)=>call('/publisher/'+op,{room,...body},{Authorization:'Bearer '+secret});
  const seal=(seq,kind,payload)=>{
    const iv=randomBytes(12), c=createCipheriv('aes-256-gcm',key,iv);c.setAAD(Buffer.from(`${room}:${seq}:${kind}`));
    return {seq,kind,data:Buffer.concat([iv,c.update(JSON.stringify(payload)),c.final(),c.getAuthTag()]).toString('base64')};
  };
  let reader, secondReader;
  try {
    assert.equal((await call('/api/state')).status,401);
    assert.equal((await call('/publisher/open',{room})).status,401);
    assert.equal((await pub('open',{})).status,200);
    assert.equal((await pub('invite',{ticket})).status,200);
    assert.equal((await call('/api/pair',{room,ticket:token()})).status,401);
    assert.equal((await call('/api/pair',{room,ticket},{Origin:'https://evil.example'})).status,403);
    const paired=await call('/api/pair',{room,ticket});assert.equal(paired.status,200);
    const setCookie=paired.headers.get('set-cookie');assert.match(setCookie,/Secure; HttpOnly; SameSite=Strict/);
    const cookie={Cookie:setCookie.split(';')[0]};
    assert.equal((await call('/api/pair',{room,ticket})).status,401);
    const device=createECDH('prime256v1');device.generateKeys();
    const recovery={id:token(),publicKey:device.getPublicKey().toString('base64')};
    assert.equal((await call('/api/restore',recovery)).status,401);
    assert.equal((await call('/api/restore',recovery,{...cookie,Origin:'https://evil.example'})).status,403);
    assert.equal((await call('/api/restore',{...recovery,publicKey:'bad'},cookie)).status,400);
    assert.equal((await call('/api/restore',recovery,cookie)).status,202);
    assert.equal((await call('/api/restore',recovery,cookie)).status,202); // idempotent poll
    assert.deepEqual((await (await pub('status',{})).json()).recoveries,[recovery]);
    const mac=createECDH('prime256v1');mac.generateKeys();
    const context=Buffer.from(`StreamTranslate recovery v1:${room}:${recovery.id}`);
    const wrapping=Buffer.from(hkdfSync('sha256',mac.computeSecret(device.getPublicKey()),Buffer.from(room),context,32));
    const nonce=randomBytes(12),cipher=createCipheriv('aes-256-gcm',wrapping,nonce);cipher.setAAD(context);
    const answer={id:recovery.id,publicKey:mac.getPublicKey().toString('base64'),data:Buffer.concat([nonce,cipher.update(key),cipher.final(),cipher.getAuthTag()]).toString('base64')};
    assert.equal((await call('/publisher/recover',{room,...answer})).status,401);
    assert.equal((await pub('recover',{...answer,id:token()})).status,404);
    assert.equal((await pub('recover',answer)).status,200);
    const restored=await call('/api/restore',recovery,cookie);assert.equal(restored.status,200);
    const sealed=await restored.json();assert.equal(sealed.room,room);assert.equal(sealed.id,recovery.id);
    assert(!JSON.stringify(sealed).includes(key.toString('hex')));
    const remoteKey=Buffer.from(hkdfSync('sha256',device.computeSecret(Buffer.from(sealed.publicKey,'base64')),Buffer.from(room),context,32));
    const box=Buffer.from(sealed.data,'base64'),decipher=createDecipheriv('aes-256-gcm',remoteKey,box.subarray(0,12));
    decipher.setAAD(context);decipher.setAuthTag(box.subarray(-16));
    assert.deepEqual(Buffer.concat([decipher.update(box.subarray(12,-16)),decipher.final()]),key);
    assert.deepEqual((await (await pub('status',{})).json()).recoveries,[]);
    const clear={sessionID:'test-session',sequence:1,captions:[{id:'one',original:'PRIVATE ORIGINAL',translation:'私密译文'}],status:'listening'};
    const frame=seal(1,'snapshot',clear);assert(!frame.data.includes('PRIVATE'));
    assert.equal((await pub('publish',{frame})).status,200);
    assert.equal((await pub('publish',{frame})).status,200);
    assert.equal((await pub('publish',{frame:seal(3,'change',{})})).status,409);
    const stream=await call('/api/events',undefined,cookie);assert.equal(stream.status,200);reader=stream.body.getReader();
    const chunk=await reader.read();const text=new TextDecoder().decode(chunk.value);
    assert(!text.includes('PRIVATE ORIGINAL'));assert(!text.includes('私密译文'));
    const received=JSON.parse(text.match(/event: sealed\ndata: (.*)\n/)[1]);
    const encrypted=Buffer.from(received.data,'base64');
    const d=createDecipheriv('aes-256-gcm',key,encrypted.subarray(0,12));
    d.setAAD(Buffer.from(`${room}:1:snapshot`));d.setAuthTag(encrypted.subarray(-16));
    assert.deepEqual(JSON.parse(Buffer.concat([d.update(encrypted.subarray(12,-16)),d.final()])),clear);
    assert.equal((await call('/api/seen',{seq:1},cookie)).status,200);
    assert.equal((await (await pub('status',{})).json()).viewers,1);
    const secondStream=await call('/api/events',undefined,cookie);assert.equal(secondStream.status,200);
    secondReader=secondStream.body.getReader();await secondReader.read();
    assert.equal((await pub('publish',{frame:seal(2,'snapshot',{...clear,sequence:2})})).status,200);
    const next=await reader.read();assert.equal(next.done,false,'second entry must not kick Safari stream off');
    assert.match(new TextDecoder().decode(next.value),/"seq":2/);
    assert.match(new TextDecoder().decode((await secondReader.read()).value),/"seq":2/);
    assert.equal((await pub('close',{})).status,200);
    assert.equal((await call('/api/state',undefined,cookie)).status,401);
    assert.equal((await call('/api/restore',recovery,cookie)).status,401);
    assert.equal((await call('/healthz?token=oops')).status,400);
  } finally {await reader?.cancel();await secondReader?.cancel();relay.closeAllConnections();await new Promise(resolve=>relay.close(resolve));}
});
